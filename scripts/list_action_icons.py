def _pixels(frame: tuple[str, dict[str, int]]) -> list[list[int | None]]:
    """把点阵展开成 0xRRGGBB 或 None（透明）；尺寸或调色板不符时报错。"""
    rows, palette = frame
    lines = rows.strip("\n").split("\n")
    if len(lines) != SIZE or any(len(line) != SIZE for line in lines):
        raise ValueError("icon frame must be 16x16")
    return [[None if mark == "." else palette[mark] for mark in line] for line in lines]


def _disabled(pixels: list[list[int | None]]) -> list[list[int | None]]:
    """经典禁用浮雕：不透明像素用阴影灰，右下偏移一像素垫白色高光。"""
    out: list[list[int | None]] = [[None] * SIZE for _ in range(SIZE)]
    for y in range(SIZE):
        for x in range(SIZE):
            if pixels[y][x] is not None and x + 1 < SIZE and y + 1 < SIZE:
                out[y + 1][x + 1] = 0xFFFFFF
    for y in range(SIZE):
        for x in range(SIZE):
            if pixels[y][x] is not None:
                out[y][x] = 0x808080
    return out


def _bmp(frames: list[list[list[int | None]]]) -> bytes:
    """按导入器约定编码 top-down BMP V4（32 位 BGRA，二值 alpha）。"""
    width, height = SIZE * len(frames), SIZE
    body = bytearray()
    for y in range(height):
        for frame in frames:
            for color in frame[y]:
                body += b"\0\0\0\0" if color is None else bytes(
                    (color & 0xFF, (color >> 8) & 0xFF, color >> 16, 0xFF))
    offset = 122
    header = struct.pack("<2sIHHI", b"BM", offset + len(body), 0, 0, offset)
    header += struct.pack("<IiiHHIIiiII", 108, width, -height, 1, 32, 3, len(body), 0, 0, 0, 0)
    header += struct.pack("<IIIII", 0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000, 0x73524742)
    header += bytes(48)
    return header + bytes(body)


def files() -> dict[str, bytes]:
    """三种状态的位图条，键为相对 `assets/classic` 的路径。悬停与默认同为彩色。"""
    colored = [_pixels(frame) for frame in FRAMES]
    variants = {"default": colored, "hot": colored, "disabled": [_disabled(frame) for frame in colored]}
    return {f"ui-original/{STRIP}-{name}-1x.bmp": _bmp(frames) for name, frames in variants.items()}


def register(manifest: dict) -> None:
    """把当前 `ui-original/` 下的文件按 ui 组登记到 manifest（原地修改）。"""
    for path in sorted(DIRECTORY.iterdir()):
        if path.is_file() and path.name != ".DS_Store":
            data = path.read_bytes()
            manifest["files"][f"ui-original/{path.name}"] = {
                "group": "ui", "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(), "origin": ORIGIN,
            }
    manifest["files"] = dict(sorted(manifest["files"].items()))


def main() -> None:
    DIRECTORY.mkdir(exist_ok=True)
    for name, data in files().items():
        (DIRECTORY.parent / name).write_bytes(data)
    path = DIRECTORY.parent / "manifest.json"
    manifest = json.loads(path.read_text())
    register(manifest)
    path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    main()
