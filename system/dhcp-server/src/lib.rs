#![no_std]
#![feature(allocator_ext)]

//! Stateful DHCPv4 allocation for one directly attached subnet.

extern crate alloc;

mod datagram;
mod leases;
mod probe;
pub use datagram::DATAGRAM_BYTES;
pub use probe::{ARP_BYTES, arp_probe};

use alloc::vec::Vec;
use core::net::Ipv4Addr;
use fallible_tree::OutOfMemory;
use packet_wire::{
    PacketError,
    dhcpv4::{Dhcpv4Builder, Dhcpv4Header, Dhcpv4Packet, MessageType},
};

use leases::{Leases, Phase};
use probe::Check;

/// Enough for a DHCP reply in a minimum 576-byte IPv4 datagram.
const REPLY_BYTES: usize = 548;
const UNSPECIFIED: Ipv4Addr = Ipv4Addr::UNSPECIFIED;

pub use router_protocol::dhcp_server::{Binding, Pool};

/// Where the adapter sends a direct DHCP reply on the interface.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Delivery {
    Broadcast,
    Unicast { address: Ipv4Addr, mac: [u8; 6] },
}

/// A serialized DHCP reply and its link-layer delivery.
pub struct Reply<'a> {
    pub delivery: Delivery,
    pub bytes: &'a [u8],
}

/// Work generated by a DHCP datagram, an ARP conflict, or a timer.
pub enum Action<'a> {
    /// Send an ARP probe before offering this address.
    Probe(Ipv4Addr),
    /// Send the complete IPv4 reply.
    Reply(Reply<'a>),
}

/// Pool setup or processing failure.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Error {
    InvalidPool,
    NoMemory,
    Packet(PacketError),
}

impl From<OutOfMemory> for Error {
    fn from(_: OutOfMemory) -> Self {
        Self::NoMemory
    }
}

impl From<PacketError> for Error {
    fn from(error: PacketError) -> Self {
        Self::Packet(error)
    }
}

struct Request {
    kind: MessageType,
    client: [u8; 256],
    client_length: usize,
    mac: [u8; 6],
    xid: u32,
    broadcast: bool,
    ciaddr: Ipv4Addr,
    requested: Option<Ipv4Addr>,
    server: Option<Ipv4Addr>,
}

impl Request {
    fn decode(packet: Dhcpv4Packet<'_>) -> Result<Option<Self>, PacketError> {
        if packet.operation() != 1
            || packet.hardware_type() != 1
            || !packet.relay_address().is_unspecified()
            || !packet.your_address().is_unspecified()
        {
            return Ok(None);
        }
        let mac: [u8; 6] = packet
            .hardware_address()
            .try_into()
            .map_err(|_| PacketError::Malformed)?;
        if mac == [0; 6] || mac[0] & 1 != 0 {
            return Err(PacketError::Malformed);
        }
        let mut client = [0; 256];
        let client_length = if let Some(id) = packet.option(61) {
            if !(2..=255).contains(&id.len()) {
                return Err(PacketError::Malformed);
            }
            client[0] = 1;
            1 + id.copy_to(&mut client[1..])?
        } else {
            client[1..7].copy_from_slice(&mac);
            7
        };
        let address = |code| {
            packet
                .option(code)
                .map(|value| value.array().map(Ipv4Addr::from))
                .transpose()
        };
        Ok(Some(Self {
            kind: packet.message_type()?,
            client,
            client_length,
            mac,
            xid: packet.transaction_id(),
            broadcast: packet.broadcast(),
            ciaddr: packet.client_address(),
            requested: address(50)?,
            server: address(54)?,
        }))
    }

    fn client(&self) -> &[u8] {
        &self.client[..self.client_length]
    }

    fn identifier(&self) -> Option<&[u8]> {
        (self.client[0] == 1).then(|| &self.client()[1..])
    }
}

/// The server for one attached subnet. Each allocator and deadline has a single owner.
pub struct Server {
    pool: Pool,
    mask: u32,
    leases: Leases,
    checks: Vec<Check>,
}

impl Server {
    /// Validate and open an empty pool. The adapter controls when the pool is reachable.
    /// # Errors
    /// Invalid host range, overlapping server or router address, unusable options, or lease duration.
    pub fn new(pool: Pool) -> Result<Self, Error> {
        let mask = pool.mask().ok_or(Error::InvalidPool)?;
        let leases = Leases::new(pool.options.first.into(), pool.options.last.into());
        Ok(Self {
            pool,
            mask,
            leases,
            checks: Vec::new(),
        })
    }

    /// Replace pool parameters, preserving leases still within the same server subnet.
    /// Addresses removed from service stay occupied until the original lease expires.
    /// # Errors
    /// The candidate pool is invalid.
    pub fn replace(&mut self, pool: Pool) -> Result<(), Error> {
        let mask = pool.mask().ok_or(Error::InvalidPool)?;
        self.cancel_checks();
        let same_link = self.pool.server == pool.server && self.mask == mask;
        self.leases.set_range(
            pool.options.first.into(),
            pool.options.last.into(),
            same_link,
        );
        self.pool = pool;
        self.mask = mask;
        Ok(())
    }

    /// Return the next actual expiry in monotonic milliseconds, if any.
    pub fn next_expiry(&self) -> Option<u64> {
        self.leases.expiry()
    }

    /// Retire expired offers, bound leases and quarantined addresses.
    pub fn expire(&mut self, now_ms: u64) {
        self.leases.expire(now_ms);
    }

    /// Iterate currently bound addresses after applying expiry at the query time.
    pub fn bindings(&mut self, after: Ipv4Addr, now_ms: u64) -> impl Iterator<Item = Binding> + '_ {
        self.expire(now_ms);
        self.leases
            .bound(u32::from(after))
            .map(|(address, hardware_address, expires_ms)| Binding {
                address: address.into(),
                hardware_address,
                expires_ms,
            })
    }

    fn handle_payload<'a>(
        &mut self,
        bytes: &[u8],
        source: Ipv4Addr,
        source_mac: [u8; 6],
        now_ms: u64,
        output: &'a mut [u8; DATAGRAM_BYTES],
    ) -> Result<Option<Action<'a>>, Error> {
        let Some(request) = Request::decode(Dhcpv4Packet::parse(bytes)?)? else {
            return Ok(None);
        };
        if request.mac != source_mac || request.ciaddr != source {
            return Ok(None);
        }
        self.expire(now_ms);
        let decision = match request.kind {
            MessageType::Discover
                if request.ciaddr.is_unspecified() && request.server.is_none() =>
            {
                return self.discover(request, now_ms, output);
            }
            MessageType::Request => self.request(&request, now_ms),
            MessageType::Decline
                if request.ciaddr.is_unspecified() && request.server == Some(self.pool.server) =>
            {
                if let Some((address, Phase::Bound | Phase::Offered(_))) =
                    self.leases.lookup(request.client())
                    && request.requested == Some(address.into())
                {
                    self.leases.decline(address, request.mac, now_ms);
                }
                None
            }
            MessageType::Release
                if request.server == Some(self.pool.server) && request.requested.is_none() =>
            {
                if let Some((address, Phase::Bound)) = self.leases.lookup(request.client())
                    && request.ciaddr == Ipv4Addr::from(address)
                {
                    self.leases.remove(address);
                }
                None
            }
            MessageType::Inform
                if request.server.is_none()
                    && request.requested.is_none()
                    && self.pool.on_link(request.ciaddr, self.mask) =>
            {
                Some((MessageType::Ack, UNSPECIFIED))
            }
            _ => None,
        };
        decision
            .map(|(kind, address)| {
                self.datagram(&request, kind, address, output)
                    .map(Action::Reply)
            })
            .transpose()
    }

    fn request(&mut self, request: &Request, now_ms: u64) -> Option<(MessageType, Ipv4Addr)> {
        let known = self.leases.lookup(request.client());
        let (address, selected) = match (
            request.ciaddr.is_unspecified(),
            request.requested,
            request.server,
        ) {
            (true, Some(_), Some(server)) if server != self.pool.server => {
                if let Some((held, Phase::Offered(xid))) = known
                    && xid == request.xid
                {
                    self.leases.remove(held);
                }
                return None;
            }
            (true, Some(address), server) => (address, server.is_some()),
            (false, None, None) => (request.ciaddr, false),
            _ => return None,
        };
        let wanted = u32::from(address);
        let bound = known == Some((wanted, Phase::Bound));
        let offered = selected && known == Some((wanted, Phase::Offered(request.xid)));
        if bound || offered {
            let expires = if self.pool.options.lease_seconds == u32::MAX {
                u64::MAX
            } else {
                now_ms.saturating_add(u64::from(self.pool.options.lease_seconds) * 1000)
            };
            self.leases.bind(wanted, request.mac, expires);
            return Some((MessageType::Ack, address));
        }
        if selected
            || !self.pool.on_link(address, self.mask)
            || matches!(known, Some((_, Phase::Bound)))
        {
            return Some((MessageType::Nak, UNSPECIFIED));
        }
        None
    }

    fn reply<'a>(
        &self,
        request: &Request,
        kind: MessageType,
        address: Ipv4Addr,
        output: &'a mut [u8; REPLY_BYTES],
    ) -> Result<Reply<'a>, Error> {
        let nak = kind == MessageType::Nak;
        let ciaddr = if nak { UNSPECIFIED } else { request.ciaddr };
        let delivery = if nak || ciaddr.is_unspecified() && request.broadcast {
            Delivery::Broadcast
        } else {
            Delivery::Unicast {
                address: if ciaddr.is_unspecified() {
                    address
                } else {
                    ciaddr
                },
                mac: request.mac,
            }
        };
        let mut builder = Dhcpv4Builder::new(
            output,
            &Dhcpv4Header {
                operation: 2,
                hardware_type: 1,
                hardware_address: &request.mac,
                hops: 0,
                transaction_id: request.xid,
                seconds: 0,
                broadcast: request.broadcast,
                client_address: ciaddr,
                your_address: address,
                server_address: UNSPECIFIED,
                relay_address: UNSPECIFIED,
                server_name: &[],
                boot_file: &[],
            },
        )?;
        builder.option(53, &[kind as u8])?;
        builder.option(54, &self.pool.server.octets())?;
        let identifier = request.identifier().unwrap_or_default();
        if !identifier.is_empty() {
            builder.option(61, identifier)?;
        }
        if !nak {
            builder.option(1, &self.mask.to_be_bytes())?;
            if let Some(router) = self.pool.options.router {
                builder.option(3, &router.octets())?;
            }
            if !address.is_unspecified() {
                builder.option(51, &self.pool.options.lease_seconds.to_be_bytes())?;
            }
            // Bound by the worst fixed options, one RFC 6842 identifier and END.
            let dns_count =
                ((REPLY_BYTES - 272 - identifier.len()) / 4).min(self.pool.options.dns.len());
            if dns_count != 0 {
                let mut dns = [[0; 4]; 63];
                for (out, server) in dns.iter_mut().zip(&self.pool.options.dns[..dns_count]) {
                    *out = server.octets();
                }
                builder.option(6, dns[..dns_count].as_flattened())?;
            }
        }
        Ok(Reply {
            delivery,
            bytes: builder.finish()?,
        })
    }
}

