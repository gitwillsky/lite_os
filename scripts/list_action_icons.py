def _mirror(frame: tuple[str, dict[str, int]]) -> tuple[str, dict[str, int]]:
    """左右镜像点阵：下一页即上一页箭头的镜像。"""
    rows, palette = frame
    return "\n" + "\n".join(row[::-1] for row in rows.strip("\n").split("\n")) + "\n", palette


